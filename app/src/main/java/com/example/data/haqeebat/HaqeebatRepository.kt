    private val surahTextCache = mutableMapOf<Int, List<String>>()

    suspend fun loadSurahVerses(surahNumber: Int): Result<List<String>> = withContext(Dispatchers.IO) {
        bundledSurahVerses[surahNumber]?.let { return@withContext Result.success(it) }
        surahTextCache[surahNumber]?.let { return@withContext Result.success(it) }

        runCatching {
            val req = Request.Builder()
                .url("https://api.alquran.cloud/v1/surah/$surahNumber/quran-uthmani")
                .header("User-Agent", "AlAnsariTV/1.0")
                .build()
            httpClient.newCall(req).execute().use { resp ->
                check(resp.isSuccessful) { "HTTP ${resp.code}" }
                val raw = resp.body?.string().orEmpty()
                val json = JSONObject(raw)
                val ayahs = json.getJSONObject("data").getJSONArray("ayahs")
                val list = mutableListOf<String>()
                for (i in 0 until ayahs.length()) {
                    val item = ayahs.getJSONObject(i)
                    val num = item.getInt("numberInSurah")
                    val text = item.getString("text").trim()
                    list.add("$text ﴿$num﴾")
                }
                surahTextCache[surahNumber] = list
                list
            }
        }
    }

